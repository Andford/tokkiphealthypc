// below and run `npm run icons` to bring in another.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(here, "node_modules", "@material-symbols", "svg-500", "rounded");

const ICONS = {
  home: "home-fill",
  clean: "mop-fill",
  storage: "hard_drive-fill",
  software: "apps",
  speed: "speed-fill",
  shield: "shield_with_heart-fill",
  build: "build-fill",
  settings: "settings-fill",
  check: "check",
  close: "close",
  info: "info-fill",
  warning: "warning-fill",
  admin: "admin_panel_settings-fill",
  refresh: "refresh",
  chevronRight: "chevron_right",
  chevronDown: "keyboard_arrow_down",
  trash: "delete-fill",
  web: "public",
  apps: "apps",
  system: "computer-fill",
  palette: "palette-fill",
  language: "language",
  pets: "pets",
  heart: "favorite-fill",
  sweep: "cleaning_services-fill",
  play: "play_arrow-fill",
  schedule: "schedule-fill",
};

let out = `// Generated by scripts/icons.mjs from Material Symbols Rounded (weight 500),
// by Google, Apache License 2.0. Paths on Material's 960 grid.

export const ICON_VIEWBOX = "0 -960 960 960";

export const ICONS = {\n`;
for (const [name, file] of Object.entries(ICONS)) {
  const svg = readFileSync(join(dir, `${file}.svg`), "utf8");
  const d = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(" ");
  out += `  // ${file}\n  ${name}: ${JSON.stringify(d)},\n`;
}
out += "} as const;\n\nexport type IconName = keyof typeof ICONS;\n";
writeFileSync(join(here, "src", "ui", "icons.ts"), out);
console.log(`wrote ${Object.keys(ICONS).length} icons`);
